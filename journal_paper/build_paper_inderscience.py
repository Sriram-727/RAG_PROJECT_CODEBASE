def runs(p, text, size=None, bold=None, italic=None, font=None):
    for part in TOKEN.split(text):
        if not part:
            continue
        if part.startswith("**"):
            r = p.add_run(part[2:-2]); r.bold = True
        elif part.startswith("*") and part.endswith("*") and len(part) > 2:
            r = p.add_run(part[1:-1]); r.italic = True
        elif part.startswith("_{"):
            r = p.add_run(part[2:-1]); r.font.subscript = True
        elif part.startswith("^{"):
            r = p.add_run(part[2:-1]); r.font.superscript = True
        else:
            r = p.add_run(part)
        r.font.name = font or FONT
        if font:
            r._r.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), font)
        if size:
            r.font.size = Pt(size)
        if bold is not None and not part.startswith("**"):
            r.bold = bold
        if italic is not None and not (part.startswith("*") and not part.startswith("**")):
            r.italic = italic
    return p


