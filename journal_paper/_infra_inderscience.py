def set_cell_border(cell, **kw):
    tcPr = cell._tc.get_or_add_tcPr()
    b = tcPr.find(qn("w:tcBorders"))
    if b is None:
        b = OxmlElement("w:tcBorders")
        tcPr.append(b)
    for edge, sz in kw.items():
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single" if sz else "nil")
        e.set(qn("w:sz"), str(sz or 0))
        e.set(qn("w:color"), "000000")
        b.append(e)


def para_border(p, **edges):
    pPr = p._p.get_or_add_pPr()
    bd = OxmlElement("w:pBdr")
    for edge, sz in edges.items():
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), str(sz))
        e.set(qn("w:space"), "4")
        e.set(qn("w:color"), "000000")
        bd.append(e)
    pPr.append(bd)


def hanging_caption(label, text, keep=True, before=8, after=4):
    cp = doc.add_paragraph()
    cp.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    cp.paragraph_format.left_indent = Cm(1.75)
    cp.paragraph_format.first_line_indent = Cm(-1.75)
    cp.paragraph_format.tab_stops.add_tab_stop(Cm(1.75))
    cp.paragraph_format.keep_with_next = keep
    cp.paragraph_format.space_before, cp.paragraph_format.space_after = Pt(before), Pt(after)
    r = cp.add_run(label)
    r.bold = True
    r.font.size = Pt(9)
    r.font.name = FONT
    cp.add_run("\t").font.size = Pt(9)
    runs(cp, text, size=9)
    return cp


