TOKEN = re.compile(r"(\*\*.+?\*\*|\*.+?\*|_\{.+?\}|\^\{.+?\})")
NOINDENT = [True]


def runs(p, text, size=None, bold=None, italic=None, font=None):
    for part in TOKEN.split(text):
        if not part:
            continue
        if part.startswith("**"):
            r = p.add_run(part[2:-2]); r.bold = True
        elif part.startswith("*") and part.endswith("*") and len(part) > 2:
            r = p.add_run(part[1:-1]); r.italic = True
        elif part.startswith("_{"):
            r = p.add_run(part[2:-1]); r.font.subscript = True
        elif part.startswith("^{"):
            r = p.add_run(part[2:-1]); r.font.superscript = True
        else:
            r = p.add_run(part)
        r.font.name = font or FONT
        if font:
            r._r.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), font)
        if size:
            r.font.size = Pt(size)
        if bold is not None and not part.startswith("**"):
            r.bold = bold
        if italic is not None and not (part.startswith("*") and not part.startswith("**")):
            r.italic = italic
    return p


def para(text, align="j", size=None, bold=None, italic=None, after=None, before=None, indent=None, keep=False,
         first=None, font=None):
    p = doc.add_paragraph()
    p.alignment = {"j": WD_ALIGN_PARAGRAPH.JUSTIFY, "c": WD_ALIGN_PARAGRAPH.CENTER, "l": WD_ALIGN_PARAGRAPH.LEFT}[align]
    if after is not None:
        p.paragraph_format.space_after = Pt(after)
    if before is not None:
        p.paragraph_format.space_before = Pt(before)
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    if keep:
        p.paragraph_format.keep_with_next = True
    use_first = (not NOINDENT[0]) if first is None else first
    if use_first and align == "j":
        p.paragraph_format.first_line_indent = Cm(0.65)
    NOINDENT[0] = False
    return runs(p, text, size, bold, italic, font)


