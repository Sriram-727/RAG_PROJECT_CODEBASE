def table(caption, header, rows, widths, size=8.5, note=None, bold_last=False):
    TABLES[0] += 1
    hanging_caption(f"Table {TABLES[0]}", caption)
    k = TEXT_W / sum(widths)
    widths = [w * k for w in widths]
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    lay = OxmlElement("w:tblLayout")
    lay.set(qn("w:type"), "fixed")
    t._tbl.tblPr.append(lay)
    for ci, w_ in enumerate(widths):
        t.columns[ci].width = Cm(w_)
    for ri, row in enumerate([header] + rows):
        for ci, val in enumerate(row):
            c = t.cell(ri, ci)
            c.width = Cm(widths[ci])
            c.text = ""
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(1.5)
            p.paragraph_format.space_before = Pt(1.5) if ri == 0 else Pt(0)
            p.paragraph_format.line_spacing = 1.0
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            runs(p, str(val), size=size, italic=True if ri == 0 else None,
                 bold=True if (bold_last and ri == len(rows)) else None)
            set_cell_border(c, top=12 if ri == 0 else 0, bottom=4 if ri == 0 else (12 if ri == len(rows) else 0),
                            left=0, right=0)
    for ri in range(len(rows) + 1):
        t.rows[ri]._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
    if note:
        para(note, size=8.5, italic=True, after=8, before=3, first=False)
    else:
        sp = doc.add_paragraph()
        sp.paragraph_format.space_after = Pt(6)
    NOINDENT[0] = True
    return t


